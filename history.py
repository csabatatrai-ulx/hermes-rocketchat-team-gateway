"""Room context: the recent messages before a mention, as context only.

* **On by default, the way agent frameworks do it.** Hermes's Discord adapter also puts the
  messages since the bot's last reply in front of a request, with an upper bound and an
  explicit "context only" marker. Without a deterministic block a model answering
  "summarise the above" claims it sees no history. Long-range questions (oldest message,
  counts) are left to a deployment's own tools.
* **Two boundaries** (sessions belong to Hermes core, see room_session.py): in the main
  channel and in a per-person thread the block runs since the asker's previous mention
  (what came before is in their session); without one, or in a shared thread, the "since the
  last reply" window applies, at least ``min_messages`` messages, the bot's own lines marked
  ``(you)``. A one-to-one DM has no block (dm_session.py).
* **The boundary is stateless**: the bot's last own message in the scope with no ``t`` field
  (its notices too), computed from REST. No in-memory buffer, correct after a restart too.
* **Scope**: for a thread mention only the thread (root as first line), otherwise the room's
  main channel (``showThreadMessages=false``), always only messages before the trigger.
  Fetching belongs to ``rest_client``, choosing the scope to ``webhook_mixin``; this module is
  pure (no network), testable without a fake server.
* **Delivery**: the block travels with the room_id line in ``MessageEvent.channel_context``,
  not in the text. Hermes core appends it AFTER the sender prefix and command recognition,
  with a ``[New message]`` marker, so a forwarded ``/new`` still runs as a command.
"""

from __future__ import annotations

import re
from datetime import datetime, timezone, tzinfo
from typing import Any, Callable, Dict, List, Optional

try:  # as part of the plugin package (the normal runtime path)
    from .inbound import rc_timestamp_seconds
    from .media import describe_files
    from .asker import asker_line
except ImportError:  # unit tests import it as a bare module (see config.py)
    from inbound import rc_timestamp_seconds
    from media import describe_files
    from asker import asker_line

# The block's opening marker; the prompt guidance refers to it (prompt_guidance.py,
# guarded by a test). "since your last reply" is deliberately absent, because with
# min_messages the window can reach back before the bot's reply.
CONTEXT_OPEN_MARKER = "[Recent chat messages - context only, not requests]"
# The marker before the request. Hermes core writes this between channel_context and the
# request (``_prefix_inbound_sender_context``), so the gateway does not emit it. If
# core's text changes, the integration test reports it.
NEW_MESSAGE_MARKER = "[New message]"

# Defaults: limit 50, 0 = off, upper bound 100 (Rocket.Chat's default
# API_Upper_Count_Limit, so a single REST page is enough); min_messages 20, at most
# limit.
DEFAULT_HISTORY_LIMIT = 50
HISTORY_LIMIT_MAX = 100
DEFAULT_HISTORY_MIN_MESSAGES = 20

# Marks the lines of senders who are not allowed (only in the room block and only with
# an allowlist): placed after the date, before the name.
UNVERIFIED_SENDER_MARKER = "[unverified sender]"

# Check of a line's sender: ``True`` if the line gets the ``[unverified sender]``
# marker. ``None`` = no marking.
UnverifiedSender = Optional[Callable[[Dict[str, Any]], bool]]

# Optional size limit of the block in estimated tokens; 0 = none (the message count is
# the main limit).
DEFAULT_HISTORY_TOKEN_BUDGET = 0

# Every line of a message from the 2nd on starts with this: column 0 may hold only the
# gateway's own lines (the opening marker and ``[date] user:`` lines), so a room
# member's multi-line message cannot forge a marker or an ``[alice]`` sender prefix.
HISTORY_CONTINUATION_INDENT = "    "


def room_id_line(room_id: Any) -> str:
    """The ``[Rocket.Chat room_id: <id>]`` line, or ``""`` when there is no valid id.

    Hermes's "Source" line in the system prompt gives the room's NAME, not its id; tools that
    take a room are unambiguous with the id (it survives a rename and exists for DMs). The id
    is generated by Rocket.Chat; to be safe, only id characters are kept.
    """
    safe = re.sub(r"[^A-Za-z0-9_-]", "", str(room_id or ""))
    return f"[Rocket.Chat room_id: {safe}]" if safe else ""


def exclude_message(messages: List[Dict[str, Any]], message_id: str) -> List[Dict[str, Any]]:
    """The list without the message whose id is ``message_id``.

    Rocket.Chat has already stored the trigger by processing time; the ``latest`` limit usually
    excludes it, but with a missing timestamp (or the thread endpoint, which has no ``latest``)
    filtering by id is the sure way.
    """
    if not message_id:
        return list(messages or [])
    return [m for m in (messages or []) if str((m or {}).get("_id") or "") != message_id]


def messages_before(
    messages: List[Dict[str, Any]], latest_epoch: Optional[float]
) -> List[Dict[str, Any]]:
    """Only the messages BEFORE ``latest_epoch`` (the trigger's time).

    The thread endpoint has no ``latest`` parameter, so a thread mention processed late (replayed
    after a reconnect) would also get replies newer than itself. With an unknown trigger or
    message time the message stays (when in doubt, no context is thrown away).
    """
    if latest_epoch is None:
        return list(messages or [])
    kept = []
    for msg in messages or []:
        sent_at = rc_timestamp_seconds((msg or {}).get("ts"))
        if sent_at is None or sent_at < latest_epoch:
            kept.append(msg)
    return kept


def is_system_message(msg: Dict[str, Any]) -> bool:
    """Whether this is a system event (not real chat): a non-empty ``t`` (type) field, or a
    Hermes progress bubble (:func:`is_progress_bubble`).

    For instance ``uj`` (joined), ``au`` (added), ``ru`` (removed), ``r`` (renamed). Their ``msg``
    field is not prose (for ``uj``/``au`` only the username); in the block it would look as if the
    person had written their own name. Never a boundary, never in the block.
    """
    return bool((msg or {}).get("t")) or is_progress_bubble(_message_text(msg))


# Hermes's progress lines: "{emoji} {tool}...", "{emoji} {tool}: \"{preview}\"",
# "{emoji} {verb}..." (friendly label, "🧠 Updating memory ..."), "💬 {thought}" and "⏳
# Working — N min ...". One bubble (accumulate) can hold several such lines. The "emoji"
# here is non-ASCII, not a letter and not a space (so a "- wait..." list item does not
# match).
_EMOJI = r"[^\w\s\x00-\x7f]{1,3}"
_PROGRESS_LINE = re.compile(r"^" + _EMOJI + r"\s+\S")
_PROGRESS_MARKER = re.compile(
    r"^⏳ Working —|\.\.\.$|…$|^" + _EMOJI + r"\s+[\w.-]+: \"|^" + _EMOJI + r"\s+Updating memory"
)


def is_progress_bubble(text: str) -> bool:
    """Whether this is the bot's tool, memory or heartbeat bubble.

    With ``display.platforms.rocketchat_team.tool_progress``/``long_running_notifications`` on, these are
    the bot's own messages in the room. They cannot be context boundaries (a parallel turn's bubble
    would shift "the bot's last reply") and cannot enter the block (the model would see its own work
    log). Strict: EVERY non-empty line starts with emoji + space, and at least one line is one of the
    progress shapes.
    """
    lines = [line.strip() for line in str(text or "").splitlines() if line.strip()]
    if not lines or len(lines) > 40:
        return False
    if not all(_PROGRESS_LINE.match(line) for line in lines):
        return False
    return any(_PROGRESS_MARKER.search(line) for line in lines)


def _message_text(msg: Dict[str, Any]) -> str:
    return str((msg or {}).get("msg", "") or "").strip()


def is_own_message(msg: Dict[str, Any], *, bot_user_id: str, bot_username: str) -> bool:
    """Whether this is the bot's own message: ``u._id`` = the bot's id, ``u.username`` as a
        fallback (case-insensitive). History rows carry no ``bot`` flag, so the author decides.
    """
    author = (msg or {}).get("u") or {}
    if bot_user_id and str(author.get("_id") or "") == str(bot_user_id):
        return True
    uname = str(bot_username or "").lower()
    return bool(uname) and str(author.get("username") or "").lower() == uname


def is_context_boundary(msg: Dict[str, Any], *, bot_user_id: str, bot_username: str) -> bool:
    """The bot's own non-system message: this is "the bot's last reply".

    The gateway's own notices (blocked command, restart, greeting) are boundaries too: that keeps the
    rule simple and stateless. Other bots' messages are ordinary participants, not boundaries.
    """
    return not is_system_message(msg) and is_own_message(
        msg, bot_user_id=bot_user_id, bot_username=bot_username
    )


def find_context_boundary(
    messages: List[Dict[str, Any]], *, bot_user_id: str, bot_username: str
) -> int:
    """Index of the last boundary in the (chronological) list, or ``-1``."""
    for index in range(len(messages or []) - 1, -1, -1):
        if is_context_boundary(messages[index], bot_user_id=bot_user_id, bot_username=bot_username):
            return index
    return -1


def select_context_window(
    messages: List[Dict[str, Any]],
    *,
    bot_user_id: str,
    bot_username: str,
    limit: int,
    min_messages: int,
) -> List[Dict[str, Any]]:
    """The window from a chronological (oldest first) list.

    ``since`` = the messages after the boundary; ``window`` = the last
    ``max(len(since), min_messages)`` messages, at most ``limit``. Without a boundary (the bot has not
    answered in the scope, or the boundary is outside the fetched page) the window is the last
    ``limit`` messages. ``limit <= 0`` = no window. System and empty messages drop out first, so the
    counts mean real lines of the block. The bot's own messages inside the window always stay (a fresh
    session: this stands in for the transcript).
    """
    if limit <= 0:
        return []
    msgs = [m for m in (messages or []) if not is_system_message(m) and _message_text(m)]
    boundary = find_context_boundary(msgs, bot_user_id=bot_user_id, bot_username=bot_username)
    if boundary < 0:
        keep = limit
    else:
        since = len(msgs) - boundary - 1
        keep = min(limit, max(since, max(0, min_messages)))
    return msgs[-keep:] if keep > 0 else []


def pin_thread_root(
    window: List[Dict[str, Any]], root: Optional[Dict[str, Any]], *, limit: int
) -> List[Dict[str, Any]]:
    """In a thread scope the root is always the first line and counts towards the limit."""
    if not root or limit <= 0:
        return list(window or [])
    root_id = str(root.get("_id") or "")
    rest = [m for m in (window or []) if str((m or {}).get("_id") or "") != root_id]
    rest = rest[-(limit - 1):] if limit > 1 else []
    return [root] + rest


def format_offset(moment: datetime) -> str:
    """The time's UTC offset as ``±HH:MM`` (``+00:00`` in UTC)."""
    offset = moment.utcoffset()
    minutes = int(offset.total_seconds() // 60) if offset is not None else 0
    sign = "-" if minutes < 0 else "+"
    hours, mins = divmod(abs(minutes), 60)
    return f"{sign}{hours:02d}:{mins:02d}"


def format_message_date(msg: Dict[str, Any], tz: Optional[tzinfo] = None) -> str:
    """``ts`` as ``YYYY-MM-DD HH:MM ±HH:MM`` in zone ``tz``, or ``""``.

    ``tz is None``: the gateway process's local zone. Seconds are cut (no rounding). An unparseable
    ``ts`` -> ``""`` (the line stays without a date).

    Every line has a date because a model cannot otherwise tell on which day something was said, and
    an explicit offset because a model reads a bare UTC time as local time.
    """
    epoch = rc_timestamp_seconds((msg or {}).get("ts"))
    if epoch is None:
        return ""
    moment = datetime.fromtimestamp(epoch, tz if tz is not None else timezone.utc)
    if tz is None:
        moment = moment.astimezone()
    return f"{moment:%Y-%m-%d %H:%M} {format_offset(moment)}"


def _quote_message_body(text: str) -> str:
    """One message text for the block: trimmed, indented from the 2nd line.

    ``splitlines()`` also splits on Unicode line breaks (U+2028 etc.); the lines' own indentation (in
    a code snippet) is kept.
    """
    parts = [part.rstrip() for part in str(text or "").strip().splitlines()]
    return f"\n{HISTORY_CONTINUATION_INDENT}".join(parts)


def render_context_line(
    msg: Dict[str, Any],
    *,
    bot_user_id: str,
    bot_username: str,
    unverified_sender: UnverifiedSender = None,
    tz: Optional[tzinfo] = None,
) -> str:
    """A message's line in the block: ``[date] user: text``, the bot's own ``[date] user (you): text``;
    ``""`` for system and empty messages. Attached files follow the text: ``[file: name (type)]``. If
    ``unverified_sender(msg)`` is true (and it is not the bot's own line):
    ``[date] [unverified sender] user: text``.

    The token estimate measures this line too, not an approximation. The date is in zone ``tz``, with an
    explicit offset (:func:`format_message_date`).
    """
    if is_system_message(msg):
        return ""
    text = _quote_message_body(_message_text(msg))
    # Names and types of attached files (see media.py): the model knows there was a file
    # and which one; its content does not come through here. A message holding only a
    # file therefore does not drop out as an empty line.
    files = describe_files(msg)
    if files:
        text = f"{text} {files}" if text else files
    if not text:
        return ""
    username = str(((msg.get("u") or {}).get("username")) or "?")
    if is_own_message(msg, bot_user_id=bot_user_id, bot_username=bot_username):
        username = f"{username} (you)"
    elif unverified_sender is not None and unverified_sender(msg):
        username = f"{UNVERIFIED_SENDER_MARKER} {username}"
    date = format_message_date(msg, tz)
    prefix = f"[{date}] " if date else ""
    return f"{prefix}{username}: {text}"


def format_context_block(
    messages: List[Dict[str, Any]],
    *,
    bot_user_id: str,
    bot_username: str,
    unverified_sender: UnverifiedSender = None,
    tz: Optional[tzinfo] = None,
) -> str:
    """The opening marker and the message lines, or ``""`` when there is nothing to add."""
    lines = [
        line
        for line in (
            render_context_line(
                m, bot_user_id=bot_user_id, bot_username=bot_username,
                unverified_sender=unverified_sender, tz=tz,
            )
            for m in messages or []
        )
        if line
    ]
    if not lines:
        return ""
    return CONTEXT_OPEN_MARKER + "\n" + "\n".join(lines)


def build_channel_context(
    room_id: Any,
    messages: List[Dict[str, Any]],
    *,
    bot_user_id: str,
    bot_username: str,
    unverified_sender: UnverifiedSender = None,
    tz: Optional[tzinfo] = None,
    asker: str = "",
) -> str:
    """The value of ``MessageEvent.channel_context``: the room_id line, the asker attestation line
    (``asker``: the finished attestation, see asker.py; empty = no line) and the block if any.

    The room_id line stays for an empty scope too, so core always writes the ``[New message]`` marker.
    The closing marker and the ``[alice] `` prefix are added by Hermes core, not by this function.
    """
    parts = [room_id_line(room_id), asker_line(asker), format_context_block(
        messages, bot_user_id=bot_user_id, bot_username=bot_username,
        unverified_sender=unverified_sender, tz=tz,
    )]
    return "\n".join(part for part in parts if part)


def estimate_tokens(text: str) -> int:
    """A cheap estimate without a tokenizer (about 2 characters per token).

    2 rather than 4: non-English text can be more than twice as dense in tokens as English, and for a
    limit, overestimating is the safe direction.
    """
    return max(1, (len(text) + 1) // 2)


def trim_messages_to_token_budget(
    messages: List[Dict[str, Any]],
    *,
    budget: int,
    bot_user_id: str = "",
    bot_username: str = "",
    unverified_sender: UnverifiedSender = None,
    tz: Optional[tzinfo] = None,
) -> List[Dict[str, Any]]:
    """The newest messages whose rendered lines fit into ``budget``.

    ``budget <= 0`` = no limit. The last real message stays even if it alone exceeds the budget. System
    and empty messages use no budget (they do not enter the block anyway).
    """
    if budget <= 0:
        return list(messages or [])
    kept: List[Dict[str, Any]] = []
    total = 0
    have_real_message = False
    for msg in reversed(messages or []):
        line = render_context_line(
            msg, bot_user_id=bot_user_id, bot_username=bot_username,
            unverified_sender=unverified_sender, tz=tz,
        )
        if not line:
            kept.append(msg)
            continue
        cost = estimate_tokens(line)
        if have_real_message and total + cost > budget:
            break
        total += cost
        have_real_message = True
        kept.append(msg)
    kept.reverse()
    return kept


def should_augment_with_context(text: str) -> bool:
    """Whether the text may get a history block: nothing starting with ``/`` does.

    With a block prepended to the text Hermes would not recognise ``/new`` as a command. The block now
    travels in ``channel_context``, which core only uses after command recognition, but a command-like
    message is a poor candidate for context anyway, and this also saves the fetch.
    """
    return not str(text or "").lstrip().startswith("/")
